namespace Sudoku.Graphics;

/// <summary>
/// Provides a house type.
/// </summary>
public enum HouseType
{
	/// <summary>
	/// Indicates unknown house type.
	/// </summary>
	Unknown = 0,

	/// <summary>
	/// Indicates row type.
	/// </summary>
	Row,

	/// <summary>
	/// Indicates column type.
	/// </summary>
	Column,

	/// <summary>
	/// Indicates nonet type.
	/// </summary>
	Nonet
}
